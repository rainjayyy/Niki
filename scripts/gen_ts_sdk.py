"""Generate a zero-dependency TypeScript client from the FastAPI OpenAPI schema.

BE-API-007. The frontend used to hand-roll a `fetch()` wrapper plus a
response `interface` for each of the 138 endpoints; every backend shape
change needed a matching frontend PR and nothing caught the drift (a TS
`as` cast is an assertion, not a check). This script turns the OpenAPI
document that FastAPI already builds into a typed client.

Usage:
    python -m scripts.gen_ts_sdk                  # write frontend/src/api/
    python scripts/gen_ts_sdk.py --out /tmp/api   # write elsewhere
    python -m scripts.gen_ts_sdk --dry-run        # print a manifest only
    python -m scripts.gen_ts_sdk --no-timestamp   # omit the header clock
    python -m scripts.gen_ts_sdk --check          # fail if output is stale

Design notes:

* No external dependencies — stdlib plus the already-installed FastAPI.
  Deliberately NOT `openapi-typescript-codegen`/`orval`: those drag an npm
  dependency tree into the backend CI and emit their own runtime abstraction
  (axios, a mutable global config singleton). We only need `fetch` and
  `interface`, and a readable/diffable emitter is ~400 lines of stdlib.

* `build_sdk(schema)` is a pure function: OpenAPI dict in, `{filename:
  contents}` out. Nothing touches the filesystem or imports `niki` — tests
  can feed it a 12-line fake schema instead of booting the app.

* Output is deterministic. Tags, operations, and models are explicitly
  sorted rather than relying on dict iteration order, so re-running with an
  unchanged backend produces byte-identical files (modulo the header
  timestamp, which `--no-timestamp` suppresses).

* One-shot generation: there is no runtime reflection in the output. When
  the backend changes, re-run the script.

Known gap (see docs/be-issues/BE-API-007.md "后续"): `multipart/form-data`
request bodies are not generated. The four affected endpoints still get a
method with their path/query parameters and a TSDoc note; the body must be
passed through `options.body` until BE-API-008 lands.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

# Make `niki` importable when run as `python scripts/gen_ts_sdk.py`.
ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DEFAULT_OUTPUT = ROOT / "frontend" / "src" / "api"

#: HTTP methods we emit, in the order they should appear inside a file.
HTTP_METHODS: tuple[str, ...] = ("get", "post", "put", "patch", "delete")

#: The TS type for "we could not work out anything better". Never `any` —
#: `unknown` forces the caller to narrow, which is the whole point of the SDK.
UNKNOWN = "unknown"

JSON_MEDIA_TYPE = "application/json"
MULTIPART_MEDIA_TYPE = "multipart/form-data"

GENERATED_BANNER = "AUTO-GENERATED by scripts/gen_ts_sdk.py (BE-API-007). DO NOT EDIT."
REGENERATE_HINT = "Re-run `make ts-sdk` after any backend route change."


# ---------------------------------------------------------------------------
# Naming helpers
# ---------------------------------------------------------------------------


def _words(text: str) -> list[str]:
    """Split an arbitrary identifier-ish string into lowercase words."""
    return [w for w in re.split(r"[^0-9A-Za-z]+", text) if w]


def pascal_case(text: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in _words(text))


def camel_case(text: str) -> str:
    pascal = pascal_case(text)
    if not pascal:
        return ""
    return pascal[:1].lower() + pascal[1:]


def ts_identifier(text: str, *, fallback: str = "Unnamed") -> str:
    """Sanitize an OpenAPI schema key into a legal TS identifier."""
    cleaned = re.sub(r"[^0-9A-Za-z_$]", "_", text).lstrip("0123456789")
    return cleaned or fallback


def slugify(text: str) -> str:
    """Turn a tag name into a filename stem (`content-policy`, `auth-audit`)."""
    return "-".join(w.lower() for w in _words(text)) or "misc"


def tag_name(tag: Any) -> str:
    """Tags may be plain strings or `{name, description}` dicts (BE-API-006)."""
    if isinstance(tag, str):
        return tag
    if isinstance(tag, dict):
        name = tag.get("name")
        if isinstance(name, str):
            return name
    return ""


def path_segments(path: str) -> list[str]:
    """Literal (non-parameter) segments of a path, minus the `/api/v1` prefix."""
    segs = [s for s in path.split("/") if s and not s.startswith("{")]
    if segs[:2] == ["api", "v1"]:
        segs = segs[2:]
    return segs


def path_param_names(path: str) -> list[str]:
    """Path parameter names in the order they appear in the URL."""
    return re.findall(r"\{([^}]+)\}", path)


def operation_base_name(method: str, path: str) -> str:
    """Derive a method name from the verb + literal path segments.

    `GET /api/v1/dashboard/weekly-report/{child_id}` -> `getDashboardWeeklyReport`.

    Path parameters are excluded so that adding a parameter does not rename an
    existing method. Collisions are resolved by the caller (see
    :func:`assign_operation_names`), which appends the parameter names.
    """
    return camel_case(" ".join([method.lower(), *path_segments(path)])) or camel_case(method)


def dedupe(name: str, taken: set[str]) -> str:
    """Return `name`, or `name2`/`name3`/... if already taken. Registers it."""
    candidate = name
    counter = 2
    while candidate in taken:
        candidate = f"{name}{counter}"
        counter += 1
    taken.add(candidate)
    return candidate


