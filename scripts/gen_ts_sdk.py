def collapse(text: str) -> str:
    """Squash a docstring-derived blob into one line fit for a TSDoc comment."""
    return re.sub(r"\s+", " ", text).replace("*/", "*\\/").strip()


def header(timestamp: str | None, *, extra: list[str] | None = None) -> list[str]:
    lines = ["/**", f" * {GENERATED_BANNER}", " *", f" * {REGENERATE_HINT}"]
    for line in extra or []:
        lines.append(f" * {line}")
    if timestamp:
        # Kept on a single line with no separator so `strip_timestamp` can
        # drop it cleanly and two runs compare equal.
        lines.append(f" * Generated: {timestamp}")
    lines.append(" */")
    return lines


def tsdoc(operation: Operation) -> list[str]:
    lines = ["/**"]
    summary = operation.summary or f"{operation.method} {operation.path}"
    lines.append(f" * {summary}")
    if operation.description and operation.description != operation.summary:
        lines.append(" *")
        lines.append(f" * {operation.description}")
    lines.append(" *")
    lines.append(f" * @remarks `{operation.method} {operation.path}`")
    for param in operation.path_params + operation.query_params:
        if param.description:
            lines.append(f" * @param {param.ts_name} - {param.description}")
    if operation.header_params:
        headers = ", ".join(f"`{h}`" for h in operation.header_params)
        lines.append(f" * @remarks header parameter(s) {headers} — pass via `options.headers`.")
    if operation.multipart:
        lines.append(
            " * @remarks multipart body not yet generated (BE-API-008) — pass a "
            "`FormData` through `options.body`."
        )
    if operation.deprecated:
        lines.append(" * @deprecated")
    lines.append(" */")
    return lines


def query_object_type(operation: Operation) -> str:
    fields = []
    for param in operation.query_params:
        optional = "" if param.required else "?"
        fields.append(f"{quote_key(param.wire_name)}{optional}: {param.ts_type}")
    return "{ " + "; ".join(fields) + " }"


def url_template(path: str, operation: Operation) -> str:
    """Build a TS template literal for the request path."""
    by_wire = {p.wire_name: p for p in operation.path_params}
    result = path
    for wire_name in path_param_names(path):
        param = by_wire.get(wire_name)
        ts_name = param.ts_name if param else camel_case(wire_name)
        result = result.replace(
            "{" + wire_name + "}", f"${{encodeURIComponent(String({ts_name}))}}"
        )
    escaped = result.replace("`", "\\`")
    return f"`{escaped}`"


def render_operation(operation: Operation) -> list[str]:
    """Emit one `export async function`."""
    # (name, type, optional) in signature order.
    args: list[tuple[str, str, bool]] = [
        (p.ts_name, p.ts_type, False) for p in operation.path_params
    ]
    if operation.body_type is not None:
        args.append(("body", operation.body_type, not operation.body_required))
    has_query = bool(operation.query_params)
    if has_query:
        query_required = any(p.required for p in operation.query_params)
        args.append(("query", query_object_type(operation), not query_required))
    args.append(("options", "RequestOptions", True))

    # TypeScript forbids a required parameter after an optional one. If a later
    # parameter is required, widen the earlier optional ones to `T | undefined`
    # (still required at the call site, but explicitly passable as undefined).
    last_required = max((i for i, (_n, _t, opt) in enumerate(args) if not opt), default=-1)
    rendered_args: list[str] = []
    for index, (arg_name, arg_type, optional) in enumerate(args):
        if optional and index < last_required:
            rendered_args.append(f"{arg_name}: {arg_type} | undefined")
        elif optional:
            rendered_args.append(f"{arg_name}?: {arg_type}")
        else:
            rendered_args.append(f"{arg_name}: {arg_type}")

    lines = tsdoc(operation)
    lines.append(f"export async function {operation.name}(")
    for arg in rendered_args:
        lines.append(f"  {arg},")
    lines.append(f"): Promise<{operation.response_type}> {{")

    init_parts = ["...options"]
    if has_query:
        init_parts.append("query")
    if operation.body_type is not None:
        init_parts.append("body")
    init = "{ " + ", ".join(init_parts) + " }"

    lines.append(f"  return request<{operation.response_type}>(")
    lines.append(f'    "{operation.method}",')
    lines.append(f"    {url_template(operation.path, operation)},")
    lines.append(f"    {init},")
    lines.append("  );")
    lines.append("}")
    return lines


def interface_body(schema: dict[str, Any], models: ModelRegistry) -> str:
    """Render the `{ ... }` block of a named interface (multi-line)."""
    properties: dict[str, Any] = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    lines = ["{"]
    for prop_name in properties:
        prop_schema = properties[prop_name] if isinstance(properties, dict) else {}
        description = collapse(
            str((prop_schema or {}).get("description") or "")
            if isinstance(prop_schema, dict)
            else ""
        )
        if description:
            lines.append(f"  /** {description} */")
        optional = "" if prop_name in required else "?"
        prop_type = ts_type(prop_schema, models)
        lines.append(f"  {quote_key(prop_name)}{optional}: {prop_type};")
    if not properties:
        lines.append(f"  [key: string]: {UNKNOWN};")
    lines.append("}")
    return "\n".join(lines)


def render_models(models: ModelRegistry, timestamp: str | None) -> str:
    lines = header(
        timestamp,
        extra=[
            "Types derived from the OpenAPI `components.schemas` block.",
            "`Body_*` interfaces describe multipart form bodies; the SDK does not",
            "generate multipart call signatures yet (BE-API-008).",
        ],
    )
    lines.append("")

    for key in sorted(models.schemas):
        schema = models.schemas[key] or {}
        name = models.names[key]
        description = collapse(str(schema.get("description") or ""))
        if description:
            lines.extend(["/**", f" * {description}", " */"])
        if isinstance(schema.get("properties"), dict) or schema.get("type") == "object":
            lines.append(f"export interface {name} {interface_body(schema, models)}")
        else:
            lines.append(f"export type {name} = {ts_type(schema, models)};")
        lines.append("")

    for name in sorted(models.inline):
        lines.append("/** Inline response schema (no named component). */")
        lines.append(f"export interface {name} {models.inline[name]}")
        lines.append("")

    if not models.schemas and not models.inline:
        lines.append("// No component schemas in the OpenAPI document.")
        lines.append("export {};")
        lines.append("")

    return "\n".join(lines)


def render_tag_module(
    tag: str,
    operations: list[Operation],
    timestamp: str | None,
    model_names: list[str],
) -> str:
    used_models = sorted(
        {
            name
            for name in model_names
            for op in operations
            if re.search(rf"\b{re.escape(name)}\b", op.response_type)
            or (op.body_type and re.search(rf"\b{re.escape(name)}\b", op.body_type))
            or any(
                re.search(rf"\b{re.escape(name)}\b", p.ts_type)
                for p in op.path_params + op.query_params
            )
        }
    )

    lines = header(
        timestamp,
        extra=[f"Endpoints tagged `{tag}` ({len(operations)} operation(s))."],
    )
    lines.append("")
    lines.append('import { request } from "./client";')
    lines.append('import type { RequestOptions } from "./client";')
    if used_models:
        lines.append("import type {")
        for name in used_models:
            lines.append(f"  {name},")
        lines.append('} from "./models";')
    lines.append("")

    for operation in sorted(operations, key=lambda op: op.sort_key):
        lines.extend(render_operation(operation))
        lines.append("")

    return "\n".join(lines)


def render_index(
    tag_files: list[str], timestamp: str | None, operation_count: int, tag_count: int
) -> str:
    lines = header(
        timestamp,
        extra=[
            f"Barrel file: {operation_count} operation(s) across {tag_count} tag(s).",
            "",
            "Usage:",
            '  import { configure, getHealth } from "@/api";',
            '  configure({ baseUrl: "https://api.niki.example", getToken });',
        ],
    )
    lines.append("")
    lines.append('export * from "./client";')
    lines.append('export * from "./models";')
    for stem in tag_files:
        lines.append(f'export * from "./{stem}";')
    lines.append("")
    return "\n".join(lines)


