def build_sdk(schema: dict[str, Any], *, timestamp: str | None = None) -> dict[str, str]:
    """Render the whole SDK. Pure: OpenAPI dict in, `{filename: text}` out."""
    components = schema.get("components") or {}
    raw_schemas = components.get("schemas") or {}
    models = ModelRegistry(raw_schemas if isinstance(raw_schemas, dict) else {})

    operations = collect_operations(schema, models)

    by_tag: dict[str, list[Operation]] = {}
    for operation in operations:
        by_tag.setdefault(operation.tag, []).append(operation)

    files: dict[str, str] = {}
    stems: list[str] = []
    used_stems: set[str] = {"client", "models", "index"}
    for tag in sorted(by_tag):
        stem = dedupe(slugify(tag), used_stems)
        stems.append(stem)
        files[f"{stem}.ts"] = render_tag_module(
            tag, by_tag[tag], timestamp, model_names=all_model_names(models)
        )

    # models.ts last: rendering the tag modules may have registered inline
    # response interfaces that must appear in it.
    files["client.ts"] = render_client(timestamp)
    files["models.ts"] = render_models(models, timestamp)
    files["index.ts"] = render_index(stems, timestamp, len(operations), len(by_tag))
    return dict(sorted(files.items()))


def all_model_names(models: ModelRegistry) -> list[str]:
    return sorted({*models.names.values(), *models.inline})


def load_schema() -> dict[str, Any]:
    """Materialise the OpenAPI document in-process (no server, no DB)."""
    from niki.main import app

    schema = app.openapi()
    return dict(schema)


def utc_timestamp() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def write_files(files: dict[str, str], out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, content in files.items():
        target = out_dir / name
        target.write_text(content, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a zero-dependency TypeScript client (BE-API-007)."
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"Output directory (default: {DEFAULT_OUTPUT.relative_to(ROOT)})",
    )
    parser.add_argument(
        "--no-timestamp",
        action="store_true",
        help="Omit the header timestamp (byte-identical reruns).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print a manifest instead of writing files.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the files on disk differ from freshly generated output.",
    )
    parser.add_argument(
        "--schema",
        type=Path,
        default=None,
        help="Read the OpenAPI document from a JSON file instead of the app.",
    )
    args = parser.parse_args(argv)

    if args.schema is not None:
        schema = json.loads(args.schema.read_text(encoding="utf-8"))
    else:
        schema = load_schema()

    timestamp = None if (args.no_timestamp or args.check) else utc_timestamp()
    files = build_sdk(schema, timestamp=timestamp)

    if args.dry_run:
        for name, content in files.items():
            print(f"{name}\t{len(content.splitlines())} lines")
        print(f"{len(files)} file(s) would be written to {args.out}")
        return 0

    if args.check:
        stale: list[str] = []
        for name, content in files.items():
            target = args.out / name
            if not target.exists():
                stale.append(f"{name} (missing)")
            elif strip_timestamp(target.read_text(encoding="utf-8")) != strip_timestamp(content):
                stale.append(f"{name} (differs)")
        if stale:
            print("Generated SDK is stale — run `make ts-sdk`:", file=sys.stderr)
            for item in stale:
                print(f"  {item}", file=sys.stderr)
            return 1
        print(f"SDK in {args.out} is up to date ({len(files)} files).")
        return 0

    written = write_files(files, args.out)
    print(f"Wrote {len(written)} TypeScript file(s) to {args.out}")
    return 0


def strip_timestamp(text: str) -> str:
    """Drop the header `Generated:` line so two runs can be compared."""
    return "\n".join(
        line for line in text.splitlines() if not line.strip().startswith("* Generated:")
    )


if __name__ == "__main__":
    raise SystemExit(main())
