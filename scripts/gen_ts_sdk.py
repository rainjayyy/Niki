class ModelRegistry:
    """Maps OpenAPI `components.schemas` keys to TypeScript interface names."""

    def __init__(self, schemas: dict[str, Any] | None = None) -> None:
        self.schemas: dict[str, Any] = dict(schemas or {})
        self.names: dict[str, str] = {}
        taken: set[str] = set()
        for key in sorted(self.schemas):
            self.names[key] = dedupe(ts_identifier(key), taken)
        #: Extra interfaces synthesised from inline schemas, `name -> body`.
        self.inline: dict[str, str] = {}
        self._inline_taken: set[str] = set(taken)

    def ref_name(self, ref: str) -> str:
        key = ref.rsplit("/", 1)[-1]
        if key in self.names:
            return self.names[key]
        # Unknown $ref target — emit something legal rather than crashing.
        return ts_identifier(key, fallback=UNKNOWN) if key else UNKNOWN

    def add_inline(self, preferred: str, body: str) -> str:
        """Register a synthesised interface, reusing an identical existing one."""
        for existing, existing_body in self.inline.items():
            if existing_body == body and existing == preferred:
                return existing
        name = dedupe(preferred, self._inline_taken)
        self.inline[name] = body
        return name


def _literal(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    if isinstance(value, str):
        return json.dumps(value)
    return UNKNOWN


def _union(parts: list[str]) -> str:
    seen: list[str] = []
    for part in parts:
        if part and part not in seen:
            seen.append(part)
    if not seen:
        return UNKNOWN
    if UNKNOWN in seen and len(seen) > 1:
        # `unknown | X` collapses to `unknown`; drop the noise.
        seen = [p for p in seen if p != UNKNOWN] or [UNKNOWN]
    return " | ".join(seen)


def ts_type(node: Any, models: ModelRegistry, *, depth: int = 0) -> str:
    """Translate an OpenAPI/JSON-Schema node into a TypeScript type.

    Anything we do not understand becomes `unknown` — never `any` — so the
    generated client still compiles under `strict` and the caller is forced
    to narrow rather than silently trusting a wrong shape.
    """
    if not isinstance(node, dict) or not node:
        return UNKNOWN
    if depth > 12:  # pathological/recursive inline schema guard
        return UNKNOWN

    if "$ref" in node:
        return models.ref_name(str(node["$ref"]))

    if "const" in node:
        return _literal(node["const"])

    if isinstance(node.get("enum"), list) and node["enum"]:
        return _union([_literal(v) for v in node["enum"]])

    for combinator in ("anyOf", "oneOf"):
        variants = node.get(combinator)
        if isinstance(variants, list) and variants:
            return _union([ts_type(v, models, depth=depth + 1) for v in variants])

    all_of = node.get("allOf")
    if isinstance(all_of, list) and all_of:
        parts = [ts_type(v, models, depth=depth + 1) for v in all_of]
        parts = [p for p in parts if p != UNKNOWN]
        if not parts:
            return UNKNOWN
        return " & ".join(dict.fromkeys(parts))

    node_type = node.get("type")
    if isinstance(node_type, list):
        return _union([ts_type({**node, "type": t}, models, depth=depth + 1) for t in node_type])

    if node_type == "array":
        item = ts_type(node.get("items"), models, depth=depth + 1)
        return f"Array<{item}>"

    if node_type == "object" or "properties" in node or "additionalProperties" in node:
        properties = node.get("properties")
        if isinstance(properties, dict) and properties:
            return object_literal(node, models, depth=depth + 1)
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts_type(extra, models, depth=depth + 1)}>"
        return f"Record<string, {UNKNOWN}>"

    if node_type == "string":
        # `bytes`/`UploadFile` form fields surface as a string with a binary
        # content type; in the browser those are `File`/`Blob` values.
        if node.get("contentMediaType") == "application/octet-stream":
            return "Blob"
        if node.get("format") == "binary":
            return "Blob"
        return "string"
    if node_type in ("integer", "number"):
        return "number"
    if node_type == "boolean":
        return "boolean"
    if node_type == "null":
        return "null"

    return UNKNOWN


def object_literal(node: dict[str, Any], models: ModelRegistry, *, depth: int) -> str:
    """Render an inline object schema as a single-line TS object type."""
    properties: dict[str, Any] = node.get("properties") or {}
    required = set(node.get("required") or [])
    fields: list[str] = []
    for prop_name in properties:
        prop_type = ts_type(properties[prop_name], models, depth=depth)
        optional = "" if prop_name in required else "?"
        fields.append(f"{quote_key(prop_name)}{optional}: {prop_type}")
    if not fields:
        return f"Record<string, {UNKNOWN}>"
    return "{ " + "; ".join(fields) + " }"


def quote_key(key: str) -> str:
    """Quote an object key unless it is a bare JS identifier."""
    if re.fullmatch(r"[A-Za-z_$][0-9A-Za-z_$]*", key):
        return key
    return json.dumps(key)


