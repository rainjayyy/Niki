@dataclass(frozen=True)
class Param:
    """A path or query parameter."""

    wire_name: str
    ts_name: str
    ts_type: str
    required: bool
    description: str = ""


@dataclass
class Operation:
    """One generated method."""

    tag: str
    method: str
    path: str
    name: str
    summary: str
    description: str
    path_params: list[Param] = field(default_factory=list)
    query_params: list[Param] = field(default_factory=list)
    header_params: list[str] = field(default_factory=list)
    body_type: str | None = None
    body_required: bool = False
    multipart: bool = False
    response_type: str = UNKNOWN
    deprecated: bool = False

    @property
    def sort_key(self) -> tuple[str, int]:
        method = self.method.lower()
        order = HTTP_METHODS.index(method) if method in HTTP_METHODS else len(HTTP_METHODS)
        return (self.path, order)


def collect_operations(schema: dict[str, Any], models: ModelRegistry) -> list[Operation]:
    """Walk `paths` and build one :class:`Operation` per HTTP operation."""
    raw: list[tuple[str, str, dict[str, Any]]] = []
    for path in schema.get("paths") or {}:
        methods = (schema["paths"] or {}).get(path) or {}
        if not isinstance(methods, dict):
            continue
        for method, info in methods.items():
            if method.lower() not in HTTP_METHODS or not isinstance(info, dict):
                continue
            raw.append((path, method.lower(), info))

    raw.sort(key=lambda item: (item[0], HTTP_METHODS.index(item[1])))
    names = assign_operation_names(raw)

    operations: list[Operation] = []
    for (path, method, info), name in zip(raw, names, strict=True):
        operations.append(build_operation(path, method, info, name, models))
    return operations


def assign_operation_names(
    raw: list[tuple[str, str, dict[str, Any]]],
) -> list[str]:
    """Pick a unique camelCase method name for every operation.

    Names come from the verb plus the literal path segments, which keeps them
    stable when a parameter is added. Two operations only collide when they
    differ solely by path parameters, in which case the parameter names are
    appended (`getMedia` / `getMediaByFileId`). A numeric suffix is the last
    resort so the output always compiles instead of silently losing a method.
    """
    base_names = [operation_base_name(method, path) for path, method, _ in raw]
    counts: dict[str, int] = {}
    for base in base_names:
        counts[base] = counts.get(base, 0) + 1

    taken: set[str] = set()
    resolved: list[str] = []
    for (path, _method, _info), base in zip(raw, base_names, strict=True):
        candidate = base
        if counts[base] > 1:
            params = path_param_names(path)
            if params:
                candidate = base + "By" + "And".join(pascal_case(p) for p in params)
        resolved.append(dedupe(candidate, taken))
    return resolved


def build_operation(
    path: str,
    method: str,
    info: dict[str, Any],
    name: str,
    models: ModelRegistry,
) -> Operation:
    tags = [tag_name(t) for t in (info.get("tags") or [])]
    tag = next((t for t in tags if t), "default")

    path_params: dict[str, Param] = {}
    query_params: list[Param] = []
    header_params: list[str] = []
    for raw_param in info.get("parameters") or []:
        if not isinstance(raw_param, dict):
            continue
        location = raw_param.get("in")
        wire_name = str(raw_param.get("name") or "")
        if not wire_name:
            continue
        param = Param(
            wire_name=wire_name,
            ts_name=camel_case(wire_name) or ts_identifier(wire_name, fallback="param"),
            ts_type=ts_type(raw_param.get("schema"), models),
            required=bool(raw_param.get("required")),
            description=collapse(str(raw_param.get("description") or "")),
        )
        if location == "path":
            path_params[wire_name] = param
        elif location == "query":
            query_params.append(param)
        elif location == "header":
            header_params.append(wire_name)

    # Path parameters follow URL order; fall back to the declared schema for
    # parameters the URL template does not mention (should not happen).
    ordered_path_params: list[Param] = []
    for wire_name in path_param_names(path):
        param = path_params.pop(wire_name, None)
        if param is None:
            param = Param(
                wire_name=wire_name,
                ts_name=camel_case(wire_name) or "param",
                ts_type="string",
                required=True,
            )
        ordered_path_params.append(param)
    ordered_path_params.extend(path_params.values())
    query_params.sort(key=lambda p: (not p.required, p.wire_name))

    body_type: str | None = None
    body_required = False
    multipart = False
    request_body = info.get("requestBody")
    if isinstance(request_body, dict):
        content = request_body.get("content") or {}
        if JSON_MEDIA_TYPE in content:
            body_schema = (content[JSON_MEDIA_TYPE] or {}).get("schema")
            body_type = ts_type(body_schema, models)
            body_required = bool(request_body.get("required"))
        elif MULTIPART_MEDIA_TYPE in content:
            # BE-API-008 will generate a `FormData` signature for these.
            multipart = True

    response_type = resolve_response_type(info, name, models)

    return Operation(
        tag=tag,
        method=method.upper(),
        path=path,
        name=name,
        summary=collapse(str(info.get("summary") or "")),
        description=collapse(str(info.get("description") or "")),
        path_params=ordered_path_params,
        query_params=query_params,
        header_params=sorted(header_params),
        body_type=body_type,
        body_required=body_required,
        multipart=multipart,
        response_type=response_type,
        deprecated=bool(info.get("deprecated")),
    )


def resolve_response_type(info: dict[str, Any], name: str, models: ModelRegistry) -> str:
    """TS type of the success response body.

    Inline object schemas that actually declare properties get a named
    `<Method>Response` interface so the frontend can import the type; the
    `additionalProperties: true` blobs FastAPI emits for `-> dict` handlers
    stay as `Record<string, unknown>`.
    """
    responses = info.get("responses") or {}
    for status in ("200", "201", "202", 200, 201, 202):
        response = responses.get(status)
        if not isinstance(response, dict):
            continue
        content = response.get("content") or {}
        media = content.get(JSON_MEDIA_TYPE)
        if not isinstance(media, dict):
            continue
        response_schema = media.get("schema")
        if not isinstance(response_schema, dict) or not response_schema:
            return UNKNOWN
        if (
            "$ref" not in response_schema
            and isinstance(response_schema.get("properties"), dict)
            and response_schema["properties"]
        ):
            body = interface_body(response_schema, models)
            return models.add_inline(f"{pascal_case(name)}Response", body)
        return ts_type(response_schema, models)
    if "204" in responses or 204 in responses:
        return "void"
    return UNKNOWN


