"""Generate the §6 endpoint table from the FastAPI app's OpenAPI schema.

Source of truth: `/openapi.json` (generated by FastAPI at runtime).
This script imports the app in-process — no need to start the server.

Usage:
    python scripts/gen_openapi_table.py             # print to stdout
    python scripts/gen_openapi_table.py --write     # write to docs/api-endpoints.md

The output is sorted by path, then method, so the table is stable.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

# Make `niki` importable when run as `python scripts/gen_openapi_table.py`.
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from niki.main import create_app  # noqa: E402

METHOD_ORDER = ["GET", "POST", "PUT", "DELETE", "PATCH"]
DEFAULT_OUTPUT = ROOT / "docs" / "api-endpoints.md"


def collect_rows() -> list[tuple[str, str, str, str]]:
    app = create_app()
    schema = app.openapi()
    paths = schema.get("paths", {})

    rows: list[tuple[str, str, str, str]] = []
    for path, methods in paths.items():
        for method, info in methods.items():
            method_upper = method.upper()
            if method_upper not in METHOD_ORDER:
                continue
            summary = info.get("summary", "").replace("|", "\\|").replace("\n", " ")
            raw_tags = info.get("tags", []) or []
            tag_names = [
                (t if isinstance(t, str) else t.get("name", ""))
                for t in raw_tags
            ]
            tags = ", ".join(t for t in tag_names if t)
            rows.append((method_upper, path, tags, summary))

    rows.sort(key=lambda r: (r[1], METHOD_ORDER.index(r[0])))
    return rows


def render_markdown(rows: list[tuple[str, str, str, str]]) -> str:
    tag_counts = Counter(tag for _m, _p, tag, _s in rows if tag)
    total = len(rows)

    # BE-API-006: per-tag coverage table. `summary_present` counts
    # endpoints whose `summary` is non-empty (always true post-sweep).
    by_tag_summary: Counter = Counter()
    by_tag_missing: Counter = Counter()
    for _m, _p, tag, summary in rows:
        first_tag = tag.split(",")[0].strip() if tag else ""
        if not first_tag:
            continue
        if summary:
            by_tag_summary[first_tag] += 1
        else:
            by_tag_missing[first_tag] += 1

    lines: list[str] = []
    lines.append("# Niki API 端点清单（自动生成）")
    lines.append("")
    lines.append(f"> 来源：`/openapi.json` · 总数：**{total} 个端点**")
    lines.append("")
    lines.append("## 分布")
    lines.append("")
    lines.append("| 切片 | 端点数 |")
    lines.append("|---|---|")
    for tag, count in sorted(tag_counts.items(), key=lambda x: -x[1]):
        lines.append(f"| {tag} | {count} |")
    lines.append("")
    lines.append("## 覆盖率（BE-API-006）")
    lines.append("")
    lines.append("按 tag 统计 `summary` 是否齐全。 **目标：所有 `Missing` 为 0。**")
    lines.append("")
    lines.append("| Tag | Endpoints | With summary | Missing summary |")
    lines.append("|---|---|---|---|")
    all_tags = sorted(set(by_tag_summary) | set(by_tag_missing))
    for tag in sorted(all_tags, key=lambda t: -(by_tag_summary[t] + by_tag_missing[t])):
        have = by_tag_summary[tag]
        miss = by_tag_missing[tag]
        lines.append(f"| {tag} | {have + miss} | {have} | {miss} |")
    total_missing = sum(by_tag_missing.values())
    lines.append("")
    if total_missing == 0:
        lines.append("✅ 100% coverage.")
    else:
        lines.append(
            f"⚠️  {total_missing} endpoint(s) still missing summary."
        )
    lines.append("")
    lines.append("## 完整清单")
    lines.append("")
    lines.append("| 方法 | 路径 | 标签 | 摘要 |")
    lines.append("|---|---|---|---|")
    for method, path, tags, summary in rows:
        lines.append(f"| {method} | `{path}` | {tags} | {summary} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help=f"Write to {DEFAULT_OUTPUT} (default: print to stdout)",
    )
    args = parser.parse_args()

    rows = collect_rows()
    content = render_markdown(rows)

    if args.write:
        DEFAULT_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        DEFAULT_OUTPUT.write_text(content, encoding="utf-8")
        print(f"Wrote {len(rows)} endpoints to {DEFAULT_OUTPUT}")
    else:
        sys.stdout.buffer.write(content.encode("utf-8"))


if __name__ == "__main__":
    main()
